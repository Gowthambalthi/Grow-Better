'use strict';

/**
 * THE POSITIVE / NEGATIVE LEDGER — the contract, not the numbers.
 *
 * The board's two side bars and the Telegram gate BOTH read this one module, so
 * the thing worth pinning is the contract between them:
 *
 *   1. EVERY strategy is on exactly ONE side. There is no third bucket a row can
 *      hide in, because a dropped row is a strategy the page silently stops
 *      showing.
 *   2. POSITIVE means NET R strictly above ZERO, after the cost — the money KEPT,
 *      not a ratio. Breakeven is not positive, and a record with no trades behind
 *      it is not a finding — those are the two ways this rule is usually got wrong.
 *      A source publishing only a profit factor is decided by the equivalent line
 *      (net PF > 1 <=> net R > 0), not by a second rule.
 *   3. The ledger AGREES WITH THE FILE IT READ. If board.json says an engine's
 *      measured net PF is 1.012, no layer above may classify it as negative.
 *   4. TELEGRAM CARRIES THE POSITIVE SIDE ONLY — the delivered ids are exactly
 *      the positive ids, by construction rather than by a second list.
 *   5. STORING A DAY IS IDEMPOTENT. This runs on a 60-second poll and a daily
 *      cron; a second call for the same day must not append a second row.
 *
 * The tests below therefore assert RELATIONSHIPS between the ledger and its
 * sources. They deliberately do not assert "OF01 is positive" as a constant: the
 * measurement is regenerated by the harness, and a test that hardcodes today's
 * verdict would have to be edited the moment the record legitimately changes
 * (which is exactly the kind of edit that hides a real regression).
 */

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const os = require('os');

const ROOT = path.resolve(__dirname, '..');
const L = require(path.join(ROOT, 'strategy-core', 'strategyLedger.js'));
const { judge } = L;

const readJSON = (p) => (fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : null);
const BOARD = readJSON(path.join(ROOT, 'data', 'terminal', 'board.json'));
const ENGINES = readJSON(path.join(ROOT, 'data', 'terminal', 'backtest_results.json'));

test('judge: breakeven is not positive, and a record without trades is not a finding', () => {
  // NET is the decider: strictly above zero, or it is not positive.
  assert.equal(judge(0, 10).classification, 'negative', 'net R exactly 0 must NOT be called positive');
  assert.equal(judge(0.001, 10).classification, 'positive');
  assert.equal(judge(10.35, 10).classification, 'positive');
  assert.equal(judge(-0.5, 10).classification, 'negative');
  // The two traps: a big number on zero trades, and no net recorded at all.
  assert.equal(judge(9.9, 0).classification, 'negative', 'no resolved trades cannot be a positive strategy');
  assert.equal(judge(null, 25).classification, 'negative', 'an unmeasured record is not a positive strategy');
  assert.equal(judge(undefined, undefined).classification, 'negative');
  // A source that publishes only a PF is decided by the EQUIVALENT line, and its
  // reason says so, rather than being classified by a second rule.
  assert.equal(judge(null, 10, 1).classification, 'negative', 'PF exactly 1 is not positive');
  assert.equal(judge(null, 10, 1.001).classification, 'positive');
  assert.equal(judge(null, 10, 0.99).classification, 'negative');
  assert.match(judge(null, 10, 1.001).reason, /no net R/, 'a PF-only decision must say so');
});

test('every strategy is on exactly one side, and none is missing', () => {
  const led = L.build();
  assert.ok(led.entries.length > 0, 'the ledger must classify at least one strategy');
  for (const e of led.entries) {
    assert.ok(['positive', 'negative'].includes(e.classification), `${e.id} has classification ${e.classification}`);
    assert.equal(typeof e.reason, 'string');
    assert.ok(e.reason.length > 0, `${e.id} must say WHY it is on its side`);
    assert.ok(e.costPct == null || e.costPct >= 0, `${e.id} must carry the cost it was measured at`);
  }
  const ids = led.entries.map((e) => e.id);
  assert.equal(new Set(ids).size, ids.length, 'an id appears twice — two rows for one strategy');
  assert.equal(led.summary.positive + led.summary.negative, led.entries.length,
    'the two sides must partition the ledger with nothing dropped');
});

test('classification is exactly the rule: net R > 0 after cost, with trades', () => {
  const led = L.build();
  for (const e of led.entries) {
    const t = Number(e.trades) || 0;
    if (t > 0 && e.netR != null) {
      assert.equal(e.classification, e.netR > 0 ? 'positive' : 'negative',
        `${e.id}: netR=${e.netR} trades=${t} was filed as ${e.classification}`);
    } else if (t > 0 && e.netPF != null) {
      // PF-only source: the equivalent line, and only that.
      assert.equal(e.classification, e.netPF > 1 ? 'positive' : 'negative',
        `${e.id}: netPF=${e.netPF} (no net R) trades=${t} was filed as ${e.classification}`);
    } else {
      assert.equal(e.classification, 'negative',
        `${e.id}: no usable record (trades=${e.trades}, netR=${e.netR}, netPF=${e.netPF}) must be negative, not unknown`);
    }
  }
});

test('the ledger agrees with the board snapshot it read (engine rows)', { skip: !BOARD || !BOARD.rules }, () => {
  const led = L.build();
  assert.ok(BOARD.rules.length > 0, 'expected measured rules in board.json');
  for (const r of BOARD.rules) {
    const e = led.byId[r.engine];
    assert.ok(e, `${r.engine} is in board.json rules but missing from the ledger`);
    assert.equal(e.classification, judge(r.netR, r.trades, r.netPF).classification,
      `${r.engine}: ledger says ${e.classification}, its own measured record says ${judge(r.netR, r.trades, r.netPF).classification}`);
    assert.equal(e.netPF, r.netPF == null ? null : Number(Number(r.netPF).toFixed(3)), `${r.engine} netPF must be the measured one`);
    assert.equal(e.trades, r.trades, `${r.engine} trade count must be the measured one`);
    assert.equal(e.maySpeak, !!r.speak, `${r.engine} speak flag must match the board's`);
  }
});

test('the ledger agrees with the setup record it read', { skip: !ENGINES || !ENGINES.engines }, () => {
  const led = L.build();
  let checked = 0;
  for (const [engine, m] of Object.entries(ENGINES.engines)) {
    for (const [setup, rec] of Object.entries(m.bySetup || {})) {
      const e = led.byId[setup];
      assert.ok(e, `${setup} is measured in backtest_results.json but missing from the ledger`);
      assert.equal(e.parent, engine, `${setup} must be filed under ${engine}`);
      assert.equal(e.classification, judge(rec.netR, rec.trades, rec.netPF).classification, `${setup} classification`);
      checked++;
    }
  }
  assert.ok(checked > 0, 'expected at least one measured setup');
});

test('every setup the registry declares is in the ledger, even one that never traded', () => {
  const { ENGINES: REG } = require(path.join(ROOT, 'strategy-core', 'engines.js'));
  const led = L.build();
  for (const eng of REG) {
    for (const s of eng.setups) {
      const e = led.byId[s.setup];
      assert.ok(e, `${s.setup} is declared by the registry but absent from the ledger`);
      assert.equal(e.parent, eng.key);
    }
  }
});

test('TELEGRAM carries the positive side only — exactly, by construction', () => {
  const led = L.build();
  const pos = led.entries.filter((e) => e.classification === 'positive').map((e) => e.id).sort();
  // The delivered set is the positive set minus the RETIRED rows: a setup removed from the
  // registry (GB02/FG02 on 2026-10-18) keeps its measured record but can never arm a call,
  // so naming it as something the phone carries would promise an alert that cannot exist.
  // The invariant that matters is unchanged and is asserted both ways below: no negative
  // strategy may be delivered, and no LIVE positive row may be dropped.
  const livePos = led.entries
    .filter((e) => e.classification === 'positive' && !e.retired).map((e) => e.id).sort();
  assert.deepEqual(led.summary.telegramIds.slice().sort(), livePos,
    'the Telegram ids must be exactly the non-retired positive ids — a negative strategy on the phone is the bug this pins');
  assert.deepEqual(led.summary.positiveIds.slice().sort(), pos, 'the ledger summary still counts every positive row');
  for (const id of led.summary.telegramIds) {
    assert.ok(!led.byId[id].retired, `${id} is retired and must not be delivered`);
  }
  for (const id of led.summary.telegramIds) {
    assert.equal(led.byId[id].classification, 'positive', `${id} is not positive and must not be delivered`);
  }
  // And the other direction: nothing negative may be silently deliverable.
  for (const e of led.entries) {
    if (e.classification === 'negative') {
      assert.ok(!led.summary.telegramIds.includes(e.id), `${e.id} is negative but was in the Telegram set`);
    }
  }
});

test('today is reported as a live tape, separate from the classification', () => {
  const led = L.build();
  assert.ok(led.today && typeof led.today.verdict === 'string');
  assert.ok(['ALL POSITIVE TODAY', 'ALL NEGATIVE TODAY', 'MIXED TODAY', 'NO LIVE TRADES'].includes(led.today.verdict),
    `unexpected today verdict ${led.today.verdict}`);
  // The live per-strategy record must never be presented as the classification.
  for (const e of led.entries) {
    if (e.live) {
      assert.equal(e.live.scope, 'engine');
      assert.ok(e.live.today, `${e.id} live record must carry a today block`);
      assert.notEqual(e.live.today.verdict, e.classification,
        'the live block must be its own verdict, not a copy of the classification');
    }
  }
});

test('storing a day is idempotent, and does not touch the real history file', () => {
  const orig = L.FILES.history;
  const tmp = path.join(os.tmpdir(), `gb-ledger-test-${process.pid}.json`);
  try {
    L.FILES.history = tmp;
    const led = L.build();
    const a = L.recordDay(led);
    const b = L.recordDay(led);
    assert.equal(b.days.length, 1, 'a second call for the same day must not append a second row');
    assert.equal(a.days[0].date, led.today.date);
    assert.equal(a.days[0].entries.length, led.entries.length, 'the stored row must hold every strategy');
    const c = L.history(5);
    assert.equal(c.back, 1);
    assert.equal(Object.keys(c.byStrategy).length, led.entries.length);
    const of = c.byStrategy[led.entries[0].id];
    assert.equal(of.length, 1, 'per-strategy history must have one row per stored day');
    assert.ok(['positive', 'negative'].includes(of[0].classification));
  } finally {
    L.FILES.history = orig;
    try { if (fs.existsSync(tmp)) fs.unlinkSync(tmp); } catch (e) { /* best effort */ }
  }
});

test('the rule text states the threshold, the cost unit and the telegram gate', () => {
  const led = L.build();
  assert.match(led.rule, /POSITIVE = measured NET R > 0/);
  assert.match(led.rule, /Telegram carries the POSITIVE rows only/);
  assert.equal(led.positiveAboveNetR, 0);
  assert.equal(led.positiveAbovePF, 1);
  // The cost unit is a documented decision (percent, so 0.05 is 5 bp) rather than
  // something a renderer has to guess. Guard it on the rows that carry a cost.
  for (const e of led.entries) {
    if (e.costPct == null) continue;
    assert.ok(e.costPct <= 1, `${e.id} costPct ${e.costPct} looks like a fraction, not a percent`);
  }
});
